func TestPackageConverter_ConvertPacmanToShed_Integration(t *testing.T) {
	// Skip if tar is not available
	if !CommandExists("tar") {
		t.Skip("tar not available, skipping integration test")
	}

	// Create a temporary directory for testing
	tempDir, err := os.MkdirTemp("", "converter-test")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(tempDir)

	// Create a mock pacman package structure
	mockPkgDir := filepath.Join(tempDir, "mock-pkg")
	os.MkdirAll(filepath.Join(mockPkgDir, "usr", "bin"), DirPermissions)
	os.WriteFile(filepath.Join(mockPkgDir, "usr", "bin", "testbin"), []byte("#!/bin/sh\necho test"), ExecPermissions)

	// Create .PKGINFO
	pkgInfo := `pkgname = testpkg
pkgver = 1.0.0-1
pkgdesc = Test package
arch = x86_64
depend = glibc
`
	os.WriteFile(filepath.Join(mockPkgDir, ".PKGINFO"), []byte(pkgInfo), FilePermissions)

	// Create .INSTALL
	install := `post_install() {
	echo "Installed!"
}
`
	os.WriteFile(filepath.Join(mockPkgDir, ".INSTALL"), []byte(install), FilePermissions)

	// Create the pacman package
	pacmanPkg := filepath.Join(tempDir, "testpkg-1.0.0-1-x86_64.pkg.tar.gz")

	// Use tar to create the package
	converter := NewPackageConverterWithCacheDir(tempDir)
	err = converter.executor([]string{"tar", "-czf", pacmanPkg, "-C", mockPkgDir, "."})
	if err != nil {
		t.Fatalf("Failed to create mock package: %v", err)
	}

	// Test conversion
	shedPath, err := converter.ConvertPacmanToShed(pacmanPkg)
	if err != nil {
		t.Fatalf("ConvertPacmanToShed failed: %v", err)
	}

	if shedPath == "" {
		t.Error("Expected non-empty shed path")
	}

	// Verify .shed file exists
	if _, err := os.Stat(shedPath); os.IsNotExist(err) {
		t.Errorf("Shed file does not exist: %s", shedPath)
	}

	// Extract and verify manifest
	shedExtract := filepath.Join(tempDir, "shed-extract")
	os.MkdirAll(shedExtract, DirPermissions)
	err = converter.executor([]string{"tar", "-xf", shedPath, "-C", shedExtract})
	if err != nil {
		t.Fatalf("Failed to extract shed package: %v", err)
	}

	// Check manifest exists
	manifestPath := filepath.Join(shedExtract, "manifest.toml")
	if _, err := os.Stat(manifestPath); os.IsNotExist(err) {
		t.Error("manifest.toml not found in shed package")
	}

	// Check files directory exists
	filesDir := filepath.Join(shedExtract, "files")
	if _, err := os.Stat(filesDir); os.IsNotExist(err) {
		t.Error("files directory not found in shed package")
	}

	// Check hooks directory exists
	hooksDir := filepath.Join(shedExtract, "hooks")
	if _, err := os.Stat(hooksDir); os.IsNotExist(err) {
		t.Error("hooks directory not found in shed package")
	}

	// Check post-install hook exists
	postInstallHook := filepath.Join(hooksDir, "post-install.sh")
	if _, err := os.Stat(postInstallHook); os.IsNotExist(err) {
		t.Error("post-install.sh not found in hooks")
	}
}

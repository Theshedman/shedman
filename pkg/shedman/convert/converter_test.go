func TestExtractFunction(t *testing.T) {
	script := `
post_install() {
	echo "Installing..."
	systemctl daemon-reload
}

pre_remove() {
	systemctl stop myservice
}
`

	postInstall := extractFunction(script, "post_install")
	if !strings.Contains(postInstall, "echo") {
		t.Errorf("Expected post_install to contain echo, got '%s'", postInstall)
	}
	if !strings.Contains(postInstall, "systemctl daemon-reload") {
		t.Errorf("Expected post_install to contain systemctl, got '%s'", postInstall)
	}

	preRemove := extractFunction(script, "pre_remove")
	if !strings.Contains(preRemove, "systemctl stop") {
		t.Errorf("Expected pre_remove to contain systemctl stop, got '%s'", preRemove)
	}

	nonExistent := extractFunction(script, "nonexistent")
	if nonExistent != "" {
		t.Errorf("Expected empty string for nonexistent function, got '%s'", nonExistent)
	}
}

func TestDetectPackageFormat(t *testing.T) {
	tests := []struct {
		path     string
		expected string
	}{
		{"package.shed", "shed"},
		{"neovim-0.10.0-1-x86_64.pkg.tar.zst", "pacman-zst"},
		{"vim-9.0.0-1-x86_64.pkg.tar.xz", "pacman-xz"},
		{"vim-9.0.0-1-x86_64.pkg.tar.gz", "pacman-gz"},
		{"package.deb", "deb"},
		{"package.rpm", "rpm"},
		{"unknown.file", "unknown"},
	}

	for _, tc := range tests {
		result := DetectPackageFormat(tc.path)
		if result != tc.expected {
			t.Errorf("DetectPackageFormat(%s) = %s, want %s", tc.path, result, tc.expected)
		}
	}
}


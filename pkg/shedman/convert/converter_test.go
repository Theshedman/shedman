func TestParsePkgInfo(t *testing.T) {
	content := `# Generated by makepkg
pkgname = neovim
pkgver = 0.10.0-1
pkgdesc = Fork of Vim aiming to improve user experience
url = https://neovim.io
builddate = 1704067200
packager = Arch Linux Packager <packager@archlinux.org>
size = 5242880
arch = x86_64
depend = libluv
depend = libuv
depend = msgpack-c
optdepend = python-pynvim: for plugins
provides = vim
conflict = vim
`

	info := ParsePkgInfo(content)

	if info.PkgName != "neovim" {
		t.Errorf("Expected pkgname 'neovim', got '%s'", info.PkgName)
	}
	if info.PkgVer != "0.10.0-1" {
		t.Errorf("Expected pkgver '0.10.0-1', got '%s'", info.PkgVer)
	}
	if info.PkgDesc != "Fork of Vim aiming to improve user experience" {
		t.Errorf("Expected pkgdesc mismatch, got '%s'", info.PkgDesc)
	}
	if len(info.Depends) != 3 {
		t.Errorf("Expected 3 depends, got %d", len(info.Depends))
	}
	if len(info.OptDepends) != 1 {
		t.Errorf("Expected 1 optdepend, got %d", len(info.OptDepends))
	}
	if len(info.Provides) != 1 {
		t.Errorf("Expected 1 provides, got %d", len(info.Provides))
	}
	if len(info.Conflicts) != 1 {
		t.Errorf("Expected 1 conflict, got %d", len(info.Conflicts))
	}
	if info.Size != 5242880 {
		t.Errorf("Expected size 5242880, got %d", info.Size)
	}
}

